#!/usr/bin/env bash
# Bundles the sources into dist/app.css + dist/app.js (2 requests instead of 21) and
# stamps ?v=<OPL.VERSION> onto the bundle URLs so phones/hosts never serve stale code.
# Edit the files in css/ and js/ — never dist/. The pre-commit hook runs this.
set -euo pipefail
cd "$(dirname "$0")/.."

CSS=(
  css/fonts.css
  css/tokens.css
  css/base.css
  css/components/primitives.css
  css/components/cards.css
  css/components/chrome.css
  css/components/flow.css
  css/screens/home.css
  css/screens/loans-overview.css
  css/screens/loan-offers.css
  css/screens/applications.css
  css/screens/kfs.css
  css/screens/nesl.css
)
JS=(
  js/core.js
  js/components.js
  js/components-flow.js
  js/fx.js
  js/variants.js
  js/data/home.js
  js/data/loans-overview.js
  js/data/loan-offers.js
  js/data/applications.js
  js/data/signed-hero.js
  js/screens/home.js
  js/screens/loans-overview.js
  js/screens/loan-offers.js
  js/screens/compare-loans.js
  js/screens/applications.js
  js/screens/kfs.js
  js/screens/nesl.js
  js/app.js
)
# Desktop view — a separate bundle, fetched only when the prototype switches to desktop,
# so the mobile first load is unchanged (README → Desktop view).
DCSS=(
  css/desktop/shell.css
  css/desktop/components.css
  css/desktop/screens/loans-overview.css
  css/desktop/screens/loan-offers.css
  css/desktop/screens/compare-loans.css
)
DJS=(
  js/desktop/ui.js
  js/desktop/data/loans-overview.js
  js/desktop/data/loan-offers.js
  js/desktop/screens/fallback.js
  js/desktop/screens/loans-overview.js
  js/desktop/screens/loan-offers.js
  js/desktop/screens/compare-loans.js
)

mkdir -p dist
{ echo "/* GENERATED by tools/build.sh — edit css/*, not this file */"
  for f in "${CSS[@]}"; do printf '\n/* ==== %s ==== */\n' "$f"; cat "$f"; done; } > dist/app.css
{ echo "/* GENERATED by tools/build.sh — edit js/*, not this file */"
  for f in "${JS[@]}"; do printf '\n/* ==== %s ==== */\n' "$f"; cat "$f"; printf '\n;\n'; done; } > dist/app.js

{ echo "/* GENERATED by tools/build.sh — edit css/desktop/*, not this file */"
  for f in "${DCSS[@]}"; do printf '\n/* ==== %s ==== */\n' "$f"; cat "$f"; done; } > dist/desktop.css
{ echo "/* GENERATED by tools/build.sh — edit js/desktop/*, not this file */"
  # Desktop icons ride inside the bundle (one request instead of ~45); D.icon reads OPL.dIcons.
  python3 -c "
import json,glob,os,re
def mini(t):
    t=re.sub(r'\s*\n\s*',' ',t.strip()); t=re.sub(r' id=\"[^\"]*\"','',t); t=re.sub(r'>\s+<','><',t)
    return re.sub(r'(\d+\.\d{2})\d+',r'\1',t)
print('window.OPL=window.OPL||{};OPL.dIcons='+json.dumps({os.path.basename(f)[:-4]: mini(open(f).read()) for f in sorted(glob.glob('assets/lazy/dsk/*.svg'))}, separators=(',',':'), ensure_ascii=False)+';')"
  for f in "${DJS[@]}"; do printf '\n/* ==== %s ==== */\n' "$f"; cat "$f"; printf '\n;\n'; done; } > dist/desktop.js

V=$(grep -o 'OPL.VERSION = "[^"]*"' js/core.js | cut -d'"' -f2)
for h in index.html library.html; do
  sed -i '' -E "s#dist/app\.(css|js)(\?v=[0-9A-Za-z.\-]*)?#dist/app.\1?v=$V#g" "$h"
done
printf 'built dist/app.css (%s KB) + dist/app.js (%s KB) · desktop %s KB + %s KB · v%s\n' "$(( $(wc -c <dist/app.css) / 1024 ))" "$(( $(wc -c <dist/app.js) / 1024 ))" "$(( $(wc -c <dist/desktop.css) / 1024 ))" "$(( $(wc -c <dist/desktop.js) / 1024 ))" "$V"
